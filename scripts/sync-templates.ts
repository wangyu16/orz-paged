/**
 * Writes src/starters.ts from assets/templates/*.md: the template skeletons as
 * string constants, so the isomorphic `newDocument` (src/assemble.ts) can start
 * a document from a template without reading files (FC-18 law 2: no
 * environment reads; FC-18 §7.3: templates are text skeletons). The text files
 * in assets/templates stay the source; run by `prebuild` and `pretest`, and
 * tests/new-document.test.ts checks the module is in sync.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const DIR = 'assets/templates';
const files = readdirSync(DIR).filter((f) => f.endsWith('.md')).sort();
const entries = files.map((f) => `  ${JSON.stringify(f.slice(0, -3))}: ${JSON.stringify(readFileSync(`${DIR}/${f}`, 'utf8'))},`);
const out = [
  '// Generated by scripts/sync-templates.ts from assets/templates/*.md — do not edit.',
  '',
  '/** The template skeletons (header + starter body) by file stem, exactly as in assets/templates. */',
  'export const STARTERS: Readonly<Record<string, string>> = Object.freeze({',
  ...entries,
  '});',
  '',
].join('\n');
let current = '';
try {
  current = readFileSync('src/starters.ts', 'utf8');
} catch {
  /* first run */
}
if (current !== out) writeFileSync('src/starters.ts', out, 'utf8');
